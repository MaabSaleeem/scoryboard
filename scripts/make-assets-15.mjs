// The files collection 15 uploads: two sponsor banners, one info-page picture
// and one info-page attachment.
//
//   node scripts/make-assets-15.mjs
//
// Drawn from SVG and written by hand rather than committed as opaque binaries, so
// a later session can see exactly what they are and rebuild identical bytes. No
// clock, no randomness.
//
// 15.6 documents adding a sponsor and the Add Sponsor dialog takes a banner; 15.3
// documents the info page, whose Pictures and Attachments blocks take a picture
// and any file at all. A real company's logo, a real photograph of a real pitch
// and a real club's paperwork are none of them things this project may put in a
// help article - so these are flat graphics and invented copy, in colours that
// are plainly not the product's own blue, and a reader can tell them from the
// app's chrome at a glance.
//
// WebP as well as PNG, because the image upload endpoints accept WebP and nothing
// else (config/api.md, "Conventions"): a PNG is refused with 415 "Unsupported
// file type" even where the dialog's own caption says PNG is allowed. The PNG is
// kept so the file is viewable in a diff.

import fs from 'node:fs';
import sharp from 'sharp';

const OUT = 'assets/15';
fs.mkdirSync(OUT, { recursive: true });

const NL = String.fromCharCode(10);

// Sponsor banners render as a wide strip, so 1600 x 400 (4:1) keeps the shape
// without asking the app to letterbox anything.
const banner = (name, tagline, bg, fg, accent) => `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="400">
  <rect width="1600" height="400" fill="${bg}"/>
  <rect x="0" y="330" width="1600" height="70" fill="${accent}"/>
  <circle cx="220" cy="165" r="110" fill="none" stroke="${accent}" stroke-width="18"/>
  <circle cx="220" cy="165" r="46" fill="${accent}"/>
  <text x="420" y="150" font-family="Arial, Helvetica, sans-serif" font-size="86"
        font-weight="bold" fill="${fg}">${name}</text>
  <text x="420" y="228" font-family="Arial, Helvetica, sans-serif" font-size="40"
        fill="${accent}">${tagline}</text>
</svg>`;

// The info page's Pictures block. 16:9, which is the shape the public Gallery
// lays out in.
const gallery = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900">
  <rect width="1600" height="900" fill="#12304A"/>
  <rect x="80" y="80" width="1440" height="740" fill="none" stroke="#7FB4E0" stroke-width="10"/>
  <circle cx="800" cy="450" r="150" fill="none" stroke="#7FB4E0" stroke-width="10"/>
  <line x1="800" y1="80" x2="800" y2="820" stroke="#7FB4E0" stroke-width="10"/>
  <text x="800" y="300" text-anchor="middle" font-family="Arial, Helvetica, sans-serif"
        font-size="90" font-weight="bold" fill="#EAF4FF">KB 15 ASTRO PARK</text>
  <text x="800" y="660" text-anchor="middle" font-family="Arial, Helvetica, sans-serif"
        font-size="46" fill="#7FB4E0">Pitch one, seen from the clubhouse</text>
</svg>`;

const FILES = [
  {
    slug: 'astro-sports',
    svg: banner('KB ASTRO SPORTS', 'Kit and equipment', '#0F2E1E', '#F4F7F2', '#7FD1A0'),
  },
  {
    slug: 'riverside-cafe',
    svg: banner('KB RIVERSIDE CAFE', 'Food and drink at the pitch', '#3A1F0B', '#FBF6EF', '#E8A33D'),
  },
  { slug: 'astro-park', svg: gallery },
];

for (const f of FILES) {
  const png = `${OUT}/${f.slug}.png`;
  const webp = `${OUT}/${f.slug}.webp`;
  const buf = Buffer.from(f.svg);
  await sharp(buf).png().toFile(png);
  await sharp(buf).webp({ quality: 90 }).toFile(webp);
  console.log(`${png}  ${fs.statSync(png).size} bytes`);
  console.log(`${webp}  ${fs.statSync(webp).size} bytes`);
}

/**
 * A one-page PDF, written by hand.
 *
 * The info page's Attachments block takes any file type - its input carries no
 * accept filter at all - and a PDF of notes for teams is what an organiser would
 * really put there. Written out rather than generated by a library so there is no
 * dependency to pin, the bytes are identical on every run, and the whole file is
 * readable in a diff.
 */
function onePagePdf(lines) {
  const content = lines
    .map((l, i) => `BT /F1 ${i === 0 ? 22 : 13} Tf 72 ${740 - i * 34} Td (${l}) Tj ET`)
    .join(NL);
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] '
      + '/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    [`<< /Length ${content.length} >>`, 'stream', content, 'endstream'].join(NL),
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  const header = `%PDF-1.4${NL}`;
  let body = '';
  const offsets = [];
  let at = header.length;
  objects.forEach((o, i) => {
    const chunk = [`${i + 1} 0 obj`, o, 'endobj', ''].join(NL);
    offsets.push(at);
    body += chunk;
    at += chunk.length;
  });

  const xrefAt = header.length + body.length;
  const xref = [`xref`, `0 ${objects.length + 1}`, '0000000000 65535 f ']
    .concat(offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n `))
    .concat(['']).join(NL);
  const trailer = ['trailer', `<< /Size ${objects.length + 1} /Root 1 0 R >>`,
    'startxref', String(xrefAt), '%%EOF', ''].join(NL);

  return Buffer.from(header + body + xref + trailer, 'latin1');
}

const pdf = `${OUT}/kb-15-cup-team-notes.pdf`;
fs.writeFileSync(pdf, onePagePdf([
  'KB 15 Cup - notes for teams',
  'Kick-off 10:00 at KB 15 Astro Park, Hackney.',
  'Group A plays 10:00 to 10:50. Group B plays 11:00 to 11:50.',
  'Bring a light kit and a dark kit. Studs only on the astro.',
  'Check the Matches tab for your pitch number on the day.',
]));
console.log(`${pdf}  ${fs.statSync(pdf).size} bytes`);
